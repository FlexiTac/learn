"""Dump OpenCV's COLORMAP_VIRIDIS LUT (used by fast_32_16.py) to models/viridis.mjs.

usage: <python with numpy+opencv> -I gen_viridis.py <out.mjs>
cv2.applyColorMap returns BGR; we store RGB triples.
"""
import sys

import cv2
import numpy as np

lut = cv2.applyColorMap(np.arange(256, dtype=np.uint8).reshape(256, 1), cv2.COLORMAP_VIRIDIS).reshape(256, 3)
rgb = [[int(b[2]), int(b[1]), int(b[0])] for b in lut]
with open(sys.argv[1], 'w') as f:
    f.write('// GENERATED by shared/extract/gen_viridis.py from OpenCV %s cv2.COLORMAP_VIRIDIS (BGR -> RGB). Do not edit.\n' % cv2.__version__)
    f.write('export const VIRIDIS_RGB = %s;\n' % str(rgb).replace(' ', ''))
print('viridis: 256 entries, first', rgb[0], 'last', rgb[-1])
